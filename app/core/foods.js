// suman a la categoría del mismo nombre o, si es nueva, se agregan al final.
[...EXTRA_SECTIONS, ...AR_SECTIONS].forEach(([cat, rows]) => {
  const sec = FOOD_SECTIONS.find(s => s[0] === cat);
  if (sec) sec[1].push(...rows); else FOOD_SECTIONS.push([cat, rows]);
});

// Lista plana con la categoría de cada alimento.
export const FOODS = [];
FOOD_SECTIONS.forEach(([cat, rows]) => rows.forEach(r => {
  const o = r[6] || {};
  const food = { name: r[0], kcal: r[1], p: r[2], c: r[3], f: r[4], portion: r[5], unit: o.ml ? "ml" : "g", cat: cat };
  if (o.src) food.src = o.src;
  if (o.crudo) food.cook = { base: "crudo", factor: o.crudo };
  else if (o.cocido) food.cook = { base: "cocido", factor: o.cocido };
  FOODS.push(food);
}));

// Valores del alimento pesado en otro estado (crudo ↔ cocido). "factor" = peso cocido /
// peso crudo: el agua que gana (arroz, fideos) o pierde (carne) cambia el peso pero no
// las calorías totales, así que cada 100 g cocidos = cada 100 g crudos / factor.
export function cookVariant(food, state){
  if (!food || !food.cook || !state || state === food.cook.base) return food;
  const k = state === "cocido" ? 1 / food.cook.factor : food.cook.factor;
  const r1 = v => Math.round(v * k * 10) / 10;
  return Object.assign({}, food, {
    kcal: Math.round(food.kcal * k), p: r1(food.p), c: r1(food.c), f: r1(food.f), cookState: state
  });
}
